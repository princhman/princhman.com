        <section>
            <h2 class="mb-3 text-xl font-semibold text-white">The short version</h2>
            <p>
                Tiempo is designed to keep your activity data private. It has no advertising, analytics,
                tracking, or third-party marketing SDKs. Your data is stored on your devices and, when
                iCloud is available, in your private iCloud database so it can stay in sync.
            </p>
        </section>

        <section>
            <h2 class="mb-3 text-xl font-semibold text-white">Information Tiempo handles</h2>
            <p>
                Tiempo stores the activities you create, their names and appearance, and the time entries
                and edits you record. Tiempo also asks Apple for an identifier associated with your iCloud
                account. The app transforms that identifier into an authentication key used to recognise
                your own nearby devices; it is not used for advertising or profiling.
            </p>
        </section>

        <section>
            <h2 class="mb-3 text-xl font-semibold text-white">How your data is used</h2>
            <p>
                Activity data is used only to provide Tiempo's tracking, history, insights, Live Activity,
                and synchronisation features. Tiempo uses Apple's CloudKit service to sync through your
                private iCloud database. Nearby sync uses your local network to exchange authenticated
                updates directly between your devices.
            </p>
        </section>

        <section>
            <h2 class="mb-3 text-xl font-semibold text-white">Sharing</h2>
            <p>
                We do not sell your data or share it with advertisers or data brokers. Apple processes data
                needed to provide iCloud, CloudKit, push notifications, and App Store services under Apple's
                own terms and privacy policy.
            </p>
        </section>

        <section>
            <h2 class="mb-3 text-xl font-semibold text-white">Retention and deletion</h2>
            <p>
                Your data remains on your devices and in your private iCloud database until you delete it.
                You can delete time entries inside Tiempo. You can also remove Tiempo's stored iCloud data
                through your Apple device's iCloud storage settings. Uninstalling the app removes its local
                data from that device but may not remove data already stored in iCloud.
            </p>
        </section>

        <section>
            <h2 class="mb-3 text-xl font-semibold text-white">Your choices</h2>
            <p>
                You can deny local-network access in System Settings, stop using iCloud for Tiempo, or use
                the app while offline. Some synchronisation features will not work when those services are
                unavailable.
            </p>
        </section>

